#!/usr/bin/env python3
"""Filter ClinVar VCF down to high-confidence Pathogenic / Likely-Pathogenic variants.

Outputs a bgzipped VCF containing only records where:
  - CLNSIG includes "Pathogenic" or "Likely_pathogenic" (and is NOT conflicting), AND
  - CLNREVSTAT is 2-star or higher:
      - criteria_provided,_multiple_submitters,_no_conflicts (2★)
      - reviewed_by_expert_panel (3★)
      - practice_guideline (4★)

Optionally renames contigs to chr-prefixed form (ClinVar's GRCh38 VCF uses
unprefixed names "1", "2", "MT"; most consumer-WGS VCFs use "chr1", "chr2", "chrM").

Usage:
    python filter_clinvar.py clinvar.vcf.gz --out clinvar.filtered.vcf.gz [--rename-chrs]
"""

from __future__ import annotations

import argparse
import gzip
import re
import shutil
import subprocess
import sys
from pathlib import Path

CLNSIG_PATHOGENIC = re.compile(
    r"\b(Pathogenic|Likely_pathogenic|Pathogenic/Likely_pathogenic|Pathogenic,_low_penetrance|Likely_pathogenic,_low_penetrance)\b"
)
CLNSIG_CONFLICTING = re.compile(r"Conflicting")
REVIEW_OK = {
    "criteria_provided,_multiple_submitters,_no_conflicts",  # 2★
    "reviewed_by_expert_panel",                              # 3★
    "practice_guideline",                                    # 4★
}

# GRCh38 chromosome naming map (ClinVar -> UCSC).
RENAME = {str(i): f"chr{i}" for i in range(1, 23)}
RENAME.update({"X": "chrX", "Y": "chrY", "MT": "chrM"})


def parse_info(info: str) -> dict:
    out = {}
    for kv in info.split(";"):
        if "=" in kv:
            k, v = kv.split("=", 1)
            out[k] = v
        else:
            out[kv] = True
    return out


def open_vcf_in(path: Path):
    return gzip.open(path, "rt") if str(path).endswith(".gz") else open(path, "r")


def filter_stream(in_handle, out_handle, rename_chrs: bool) -> tuple[int, int]:
    n_in = n_out = 0
    for line in in_handle:
        if line.startswith("##"):
            if rename_chrs and line.startswith("##contig=<ID="):
                m = re.match(r"^(##contig=<ID=)([^,>]+)(.*)$", line)
                if m and m.group(2) in RENAME:
                    line = f"{m.group(1)}{RENAME[m.group(2)]}{m.group(3)}"
            out_handle.write(line)
            continue
        if line.startswith("#CHROM"):
            out_handle.write(
                "##FILTER=<ID=PASS,Description=\"All filters passed\">\n"
                f"##genome_screen_filter=\"P/LP, review_status>=2-star, generated by filter_clinvar.py\"\n"
            )
            out_handle.write(line)
            continue
        n_in += 1
        cols = line.rstrip("\n").split("\t")
        if len(cols) < 8:
            continue
        chrom, pos, vid, ref, alt, qual, flt, info = cols[:8]
        info_d = parse_info(info)
        clnsig = info_d.get("CLNSIG", "")
        clnrev = info_d.get("CLNREVSTAT", "")
        if CLNSIG_CONFLICTING.search(clnsig):
            continue
        if not CLNSIG_PATHOGENIC.search(clnsig):
            continue
        if clnrev not in REVIEW_OK:
            continue
        if rename_chrs and chrom in RENAME:
            chrom = RENAME[chrom]
        out_handle.write("\t".join([chrom, pos, vid, ref, alt, qual, flt, info]) + "\n")
        n_out += 1
    return n_in, n_out


def have(cmd: str) -> bool:
    return shutil.which(cmd) is not None


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("clinvar", type=Path, help="ClinVar VCF (gzipped)")
    ap.add_argument("--out", type=Path, required=True, help="Output VCF.gz path")
    ap.add_argument(
        "--rename-chrs",
        action="store_true",
        help="Rewrite contigs from '1' to 'chr1' (GRCh38 ClinVar ↔ UCSC convention)",
    )
    args = ap.parse_args()

    if not args.clinvar.exists():
        print(f"ERROR: ClinVar VCF not found: {args.clinvar}", file=sys.stderr)
        return 1

    # Write to a plain .vcf first, then bgzip + tabix (bgzip is needed for index-ability).
    tmp_vcf = args.out.with_suffix("").with_suffix(".vcf")
    with open_vcf_in(args.clinvar) as fin, open(tmp_vcf, "w") as fout:
        n_in, n_out = filter_stream(fin, fout, args.rename_chrs)

    print(f"ClinVar variants processed: {n_in:,}", file=sys.stderr)
    print(f"P/LP, >=2-star kept:        {n_out:,}", file=sys.stderr)

    if not have("bgzip") or not have("tabix"):
        print("WARNING: bgzip/tabix not on PATH; leaving uncompressed VCF at "
              f"{tmp_vcf}. Install htslib (conda install -c bioconda htslib).",
              file=sys.stderr)
        return 0

    # bgzip in place; htslib's bgzip overwrites the input.
    subprocess.check_call(["bgzip", "-f", str(tmp_vcf)])
    bgzipped = tmp_vcf.with_suffix(".vcf.gz")
    if bgzipped != args.out:
        bgzipped.rename(args.out)
    subprocess.check_call(["tabix", "-p", "vcf", "-f", str(args.out)])
    print(f"Wrote {args.out} (+ .tbi)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
